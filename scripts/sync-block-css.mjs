// Single source of the academic block styles: src/academic/blocks.css.
// Copies it into the two places that need a copy:
//  - styles.css, between two markers (Obsidian loads that file);
//  - src/academic/blocks-css.ts (the export embeds the same text).
// `npm run build` runs this first; a unit test fails if either copy drifts.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const BEGIN = "/* >>> academic blocks (generated from src/academic/blocks.css: do not edit) >>> */";
export const END = "/* <<< academic blocks <<< */";

export function render() {
  const css = readFileSync(join(root, "src/academic/blocks.css"), "utf8").trimEnd() + "\n";
  const ts =
    "// Generated by scripts/sync-block-css.mjs from blocks.css. Do not edit.\n" +
    `export const BLOCKS_CSS = ${JSON.stringify(css)};\n`;
  const styles = readFileSync(join(root, "styles.css"), "utf8");
  const block = `${BEGIN}\n${css}${END}\n`;
  const a = styles.indexOf(BEGIN);
  const b = styles.indexOf(END);
  const next = a >= 0 && b > a
    ? styles.slice(0, a) + block + styles.slice(b + END.length).replace(/^\n/, "")
    : styles.trimEnd() + "\n\n" + block;
  return { css, ts, styles: next };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render();
  writeFileSync(join(root, "src/academic/blocks-css.ts"), out.ts);
  writeFileSync(join(root, "styles.css"), out.styles);
}
